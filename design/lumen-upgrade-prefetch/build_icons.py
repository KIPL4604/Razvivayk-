"""Extract lossless weapon icons from original atlas cells, preserving RGBA pixels."""
import hashlib
import json
from pathlib import Path
import subprocess
from PIL import Image

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
ART = ROOT / 'webapp/frontend/assets/lumen'
DEST = ART / 'weapon-icons'
MODULE = ROOT / 'webapp/frontend/js/lumen/weapon-icon-data.mjs'


def main():
    weapons = json.loads(subprocess.check_output([
        'node', '--input-type=module', '-e',
        "import {WEAPONS} from './webapp/frontend/js/lumen/catalog.mjs';process.stdout.write(JSON.stringify(WEAPONS));"
    ], cwd=ROOT, text=True, encoding='utf-8'))
    DEST.mkdir(exist_ok=True)
    records = {}
    for name, weapon in weapons.items():
        index = weapon['index']
        sheet, cell, columns = ('weapons.png', index, 8) if index < 8 else (
            ('expedition.png', index - 8, 5) if index < 14 else ('expansion-items.png', index - 14, 8))
        with Image.open(ART / sheet) as source:
            x, y = cell % columns * 48, cell // columns * 48
            icon = source.convert('RGBA').crop((x, y, x + 48, y + 48))
        temporary = DEST / f'{name}.webp'
        icon.save(temporary, 'WEBP', lossless=True, exact=True, method=6)
        data = temporary.read_bytes()
        digest = hashlib.sha256(data).hexdigest()
        target = DEST / f'{name}-{digest[:12]}.webp'
        temporary.replace(target)
        with Image.open(target) as decoded:
            assert icon.tobytes() == decoded.convert('RGBA').tobytes(), name
        records[name] = {'file': 'weapon-icons/' + target.name, 'bytes': len(data),
                         'sha256': digest, 'source': sheet, 'cell': cell, 'columns': columns}
    MODULE.write_text('// Generated by design/lumen-upgrade-prefetch/build_icons.py.\n'
                      + 'export const WEAPON_ICONS=Object.freeze('
                      + json.dumps(records, ensure_ascii=False, indent=2) + ');\n', encoding='utf-8')
    (HERE / 'icons.json').write_text(json.dumps(records, indent=2) + '\n', encoding='utf-8')
    print(json.dumps({'icons': len(records), 'bytes': sum(r['bytes'] for r in records.values()),
                      'largest': max(r['bytes'] for r in records.values())}))


if __name__ == '__main__':
    main()
